//! the rounds on eight lanes, as assembly text

/// Half of the mixing function on four independent groups of words (a, b, c, d) at
/// once: a += b + m; d = (d ^ a) rotated by a byte shuffle; c += d; b = (b ^ c)
/// rotated right by `$right`. The first group's c is the state word kept in memory at
/// [rdx]; ymm8 holds the shuffle, then that c, then the shifted halves.
macro_rules! half {
    (($a0:literal, $b0:literal, $d0:literal), ($a1:literal, $b1:literal, $c1:literal, $d1:literal),
     ($a2:literal, $b2:literal, $c2:literal, $d2:literal), ($a3:literal, $b3:literal, $c3:literal, $d3:literal),
     $m0:literal, $m1:literal, $m2:literal, $m3:literal, $shuffle:literal, $right:literal, $left:literal) => {
        concat!(
            "vpaddd ",
            $a0,
            ", ",
            $a0,
            ", ymmword ptr [rdi + ",
            $m0,
            "*32]\n",
            "vpaddd ",
            $a1,
            ", ",
            $a1,
            ", ymmword ptr [rdi + ",
            $m1,
            "*32]\n",
            "vpaddd ",
            $a2,
            ", ",
            $a2,
            ", ymmword ptr [rdi + ",
            $m2,
            "*32]\n",
            "vpaddd ",
            $a3,
            ", ",
            $a3,
            ", ymmword ptr [rdi + ",
            $m3,
            "*32]\n",
            "vpaddd ",
            $a0,
            ", ",
            $a0,
            ", ",
            $b0,
            "\n",
            "vpaddd ",
            $a1,
            ", ",
            $a1,
            ", ",
            $b1,
            "\n",
            "vpaddd ",
            $a2,
            ", ",
            $a2,
            ", ",
            $b2,
            "\n",
            "vpaddd ",
            $a3,
            ", ",
            $a3,
            ", ",
            $b3,
            "\n",
            "vpxor ",
            $d0,
            ", ",
            $d0,
            ", ",
            $a0,
            "\n",
            "vpxor ",
            $d1,
            ", ",
            $d1,
            ", ",
            $a1,
            "\n",
            "vpxor ",
            $d2,
            ", ",
            $d2,
            ", ",
            $a2,
            "\n",
            "vpxor ",
            $d3,
            ", ",
            $d3,
            ", ",
            $a3,
            "\n",
            "vbroadcasti128 ymm8, xmmword ptr [rcx + ",
            $shuffle,
            "]\n",
            "vpshufb ",
            $d0,
            ", ",
            $d0,
            ", ymm8\n",
            "vpshufb ",
            $d1,
            ", ",
            $d1,
            ", ymm8\n",
            "vpshufb ",
            $d2,
            ", ",
            $d2,
            ", ymm8\n",
            "vpshufb ",
            $d3,
            ", ",
            $d3,
            ", ymm8\n",
            "vpaddd ymm8, ",
            $d0,
            ", ymmword ptr [rdx]\n",
            "vpaddd ",
            $c1,
            ", ",
            $c1,
            ", ",
            $d1,
            "\n",
            "vpaddd ",
            $c2,
            ", ",
            $c2,
            ", ",
            $d2,
            "\n",
            "vpaddd ",
            $c3,
            ", ",
            $c3,
            ", ",
            $d3,
            "\n",
            "vpxor ",
            $b0,
            ", ",
            $b0,
            ", ymm8\n",
            "vpxor ",
            $b1,
            ", ",
            $b1,
            ", ",
            $c1,
            "\n",
            "vpxor ",
            $b2,
            ", ",
            $b2,
            ", ",
            $c2,
            "\n",
            "vpxor ",
            $b3,
            ", ",
            $b3,
            ", ",
            $c3,
            "\n",
            "vmovdqa ymmword ptr [rdx], ymm8\n",
            "vpsrld ymm8, ",
            $b0,
            ", ",
            $right,
            "\n",
            "vpslld ",
            $b0,
            ", ",
            $b0,
            ", ",
            $left,
            "\n",
            "vpor ",
            $b0,
            ", ",
            $b0,
            ", ymm8\n",
            "vpsrld ymm8, ",
            $b1,
            ", ",
            $right,
            "\n",
            "vpslld ",
            $b1,
            ", ",
            $b1,
            ", ",
            $left,
            "\n",
            "vpor ",
            $b1,
            ", ",
            $b1,
            ", ymm8\n",
            "vpsrld ymm8, ",
            $b2,
            ", ",
            $right,
            "\n",
            "vpslld ",
            $b2,
            ", ",
            $b2,
            ", ",
            $left,
            "\n",
            "vpor ",
            $b2,
            ", ",
            $b2,
            ", ymm8\n",
            "vpsrld ymm8, ",
            $b3,
            ", ",
            $right,
            "\n",
            "vpslld ",
            $b3,
            ", ",
            $b3,
            ", ",
            $left,
            "\n",
            "vpor ",
            $b3,
            ", ",
            $b3,
            ", ymm8\n",
        )
    };
}

/// One round on the message words in the given order: the four columns, then the four
/// diagonals, each in two halves. State word n is in ymm n, except word 8 in memory.
macro_rules! round {
    ($s0:literal, $s1:literal, $s2:literal, $s3:literal, $s4:literal, $s5:literal, $s6:literal, $s7:literal,
     $s8:literal, $s9:literal, $s10:literal, $s11:literal, $s12:literal, $s13:literal, $s14:literal, $s15:literal) => {
        concat!(
            half!(
                ("ymm0", "ymm4", "ymm12"),
                ("ymm1", "ymm5", "ymm9", "ymm13"),
                ("ymm2", "ymm6", "ymm10", "ymm14"),
                ("ymm3", "ymm7", "ymm11", "ymm15"),
                $s0,
                $s2,
                $s4,
                $s6,
                0,
                12,
                20
            ),
            half!(
                ("ymm0", "ymm4", "ymm12"),
                ("ymm1", "ymm5", "ymm9", "ymm13"),
                ("ymm2", "ymm6", "ymm10", "ymm14"),
                ("ymm3", "ymm7", "ymm11", "ymm15"),
                $s1,
                $s3,
                $s5,
                $s7,
                16,
                7,
                25
            ),
            half!(
                ("ymm2", "ymm7", "ymm13"),
                ("ymm0", "ymm5", "ymm10", "ymm15"),
                ("ymm1", "ymm6", "ymm11", "ymm12"),
                ("ymm3", "ymm4", "ymm9", "ymm14"),
                $s12,
                $s8,
                $s10,
                $s14,
                0,
                12,
                20
            ),
            half!(
                ("ymm2", "ymm7", "ymm13"),
                ("ymm0", "ymm5", "ymm10", "ymm15"),
                ("ymm1", "ymm6", "ymm11", "ymm12"),
                ("ymm3", "ymm4", "ymm9", "ymm14"),
                $s13,
                $s9,
                $s11,
                $s15,
                16,
                7,
                25
            ),
        )
    };
}
