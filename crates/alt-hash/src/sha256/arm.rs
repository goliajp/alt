//! SHA-256 compression with the ARMv8 cryptography extension.

use super::K;

/// Four rounds per pair of instructions.
/// v0: a b c d, v1: e f g h, v4-v7: schedule, v16: schedule plus constant,
/// v17: a b c d before the group, v18 / v19: state at block entry, x3: constant cursor.
#[target_feature(enable = "sha2")]
pub(super) unsafe fn compress(state: &mut [u32; 8], blocks: &[u8]) {
    let count = blocks.len() / 64;
    if count == 0 {
        return;
    }
    unsafe {
        std::arch::asm!(
            "ld1 {{v0.4s, v1.4s}}, [x0]",
            "2:",
            "ld1 {{v4.16b, v5.16b, v6.16b, v7.16b}}, [x1], #64",
            "rev32 v4.16b, v4.16b",
            "rev32 v5.16b, v5.16b",
            "rev32 v6.16b, v6.16b",
            "rev32 v7.16b, v7.16b",
            "mov v18.16b, v0.16b",
            "mov v19.16b, v1.16b",
            "mov x3, x4",
            "ld1 {{v16.4s}}, [x3], #16",
            "add v16.4s, v16.4s, v4.4s",
            "mov v17.16b, v0.16b",
            "sha256h q0, q1, v16.4s",
            "sha256h2 q1, q17, v16.4s",
            "sha256su0 v4.4s, v5.4s",
            "sha256su1 v4.4s, v6.4s, v7.4s",
            "ld1 {{v16.4s}}, [x3], #16",
            "add v16.4s, v16.4s, v5.4s",
            "mov v17.16b, v0.16b",
            "sha256h q0, q1, v16.4s",
            "sha256h2 q1, q17, v16.4s",
            "sha256su0 v5.4s, v6.4s",
            "sha256su1 v5.4s, v7.4s, v4.4s",
            "ld1 {{v16.4s}}, [x3], #16",
            "add v16.4s, v16.4s, v6.4s",
            "mov v17.16b, v0.16b",
            "sha256h q0, q1, v16.4s",
            "sha256h2 q1, q17, v16.4s",
            "sha256su0 v6.4s, v7.4s",
            "sha256su1 v6.4s, v4.4s, v5.4s",
            "ld1 {{v16.4s}}, [x3], #16",
            "add v16.4s, v16.4s, v7.4s",
            "mov v17.16b, v0.16b",
            "sha256h q0, q1, v16.4s",
            "sha256h2 q1, q17, v16.4s",
            "sha256su0 v7.4s, v4.4s",
            "sha256su1 v7.4s, v5.4s, v6.4s",
            "ld1 {{v16.4s}}, [x3], #16",
            "add v16.4s, v16.4s, v4.4s",
            "mov v17.16b, v0.16b",
            "sha256h q0, q1, v16.4s",
            "sha256h2 q1, q17, v16.4s",
            "sha256su0 v4.4s, v5.4s",
            "sha256su1 v4.4s, v6.4s, v7.4s",
            "ld1 {{v16.4s}}, [x3], #16",
            "add v16.4s, v16.4s, v5.4s",
            "mov v17.16b, v0.16b",
            "sha256h q0, q1, v16.4s",
            "sha256h2 q1, q17, v16.4s",
            "sha256su0 v5.4s, v6.4s",
            "sha256su1 v5.4s, v7.4s, v4.4s",
            "ld1 {{v16.4s}}, [x3], #16",
            "add v16.4s, v16.4s, v6.4s",
            "mov v17.16b, v0.16b",
            "sha256h q0, q1, v16.4s",
            "sha256h2 q1, q17, v16.4s",
            "sha256su0 v6.4s, v7.4s",
            "sha256su1 v6.4s, v4.4s, v5.4s",
            "ld1 {{v16.4s}}, [x3], #16",
            "add v16.4s, v16.4s, v7.4s",
            "mov v17.16b, v0.16b",
            "sha256h q0, q1, v16.4s",
            "sha256h2 q1, q17, v16.4s",
            "sha256su0 v7.4s, v4.4s",
            "sha256su1 v7.4s, v5.4s, v6.4s",
            "ld1 {{v16.4s}}, [x3], #16",
            "add v16.4s, v16.4s, v4.4s",
            "mov v17.16b, v0.16b",
            "sha256h q0, q1, v16.4s",
            "sha256h2 q1, q17, v16.4s",
            "sha256su0 v4.4s, v5.4s",
            "sha256su1 v4.4s, v6.4s, v7.4s",
            "ld1 {{v16.4s}}, [x3], #16",
            "add v16.4s, v16.4s, v5.4s",
            "mov v17.16b, v0.16b",
            "sha256h q0, q1, v16.4s",
            "sha256h2 q1, q17, v16.4s",
            "sha256su0 v5.4s, v6.4s",
            "sha256su1 v5.4s, v7.4s, v4.4s",
            "ld1 {{v16.4s}}, [x3], #16",
            "add v16.4s, v16.4s, v6.4s",
            "mov v17.16b, v0.16b",
            "sha256h q0, q1, v16.4s",
            "sha256h2 q1, q17, v16.4s",
            "sha256su0 v6.4s, v7.4s",
            "sha256su1 v6.4s, v4.4s, v5.4s",
            "ld1 {{v16.4s}}, [x3], #16",
            "add v16.4s, v16.4s, v7.4s",
            "mov v17.16b, v0.16b",
            "sha256h q0, q1, v16.4s",
            "sha256h2 q1, q17, v16.4s",
            "sha256su0 v7.4s, v4.4s",
            "sha256su1 v7.4s, v5.4s, v6.4s",
            "ld1 {{v16.4s}}, [x3], #16",
            "add v16.4s, v16.4s, v4.4s",
            "mov v17.16b, v0.16b",
            "sha256h q0, q1, v16.4s",
            "sha256h2 q1, q17, v16.4s",
            "ld1 {{v16.4s}}, [x3], #16",
            "add v16.4s, v16.4s, v5.4s",
            "mov v17.16b, v0.16b",
            "sha256h q0, q1, v16.4s",
            "sha256h2 q1, q17, v16.4s",
            "ld1 {{v16.4s}}, [x3], #16",
            "add v16.4s, v16.4s, v6.4s",
            "mov v17.16b, v0.16b",
            "sha256h q0, q1, v16.4s",
            "sha256h2 q1, q17, v16.4s",
            "ld1 {{v16.4s}}, [x3], #16",
            "add v16.4s, v16.4s, v7.4s",
            "mov v17.16b, v0.16b",
            "sha256h q0, q1, v16.4s",
            "sha256h2 q1, q17, v16.4s",
            "add v0.4s, v0.4s, v18.4s",
            "add v1.4s, v1.4s, v19.4s",
            "subs x2, x2, #1",
            "b.ne 2b",
            "st1 {{v0.4s, v1.4s}}, [x0]",
            in("x0") state.as_mut_ptr(),
            inout("x1") blocks.as_ptr() => _,
            inout("x2") count => _,
            out("x3") _,
            in("x4") K.as_ptr(),
            out("v0") _, out("v1") _, out("v4") _, out("v5") _, out("v6") _, out("v7") _,
            out("v16") _, out("v17") _, out("v18") _, out("v19") _,
            options(nostack),
        );
    }
}
