//! the message schedule of two blocks at once, as assembly text

/// loads one group of four words of the two blocks at `$p`
macro_rules! load {
    ($g:literal, $y:literal, $x:literal, $p:literal) => {
        concat!(
            "vmovdqu ",
            $x,
            ", xmmword ptr [",
            $p,
            " + ",
            $g,
            "*16]\n",
            "vinserti128 ",
            $y,
            ", ",
            $y,
            ", xmmword ptr [",
            $p,
            " + 64 + ",
            $g,
            "*16], 1\n",
            "vpshufb ",
            $y,
            ", ",
            $y,
            ", ymm9\n",
            "vpaddd ymm10, ",
            $y,
            ", ymm12\n",
            "vmovdqa ymmword ptr [r11 + ",
            $g,
            "*32], ymm10\n",
        )
    };
}

/// Schedule group `$g` for words 16..32 into `$w`, from the groups one to four back.
/// The last word of a group depends on its first, which is patched in at the end.
macro_rules! early {
    ($g:literal, $k:literal, $w:literal, $p1:literal, $p2:literal, $p3:literal, $p4:literal) => {
        concat!(
            "vpalignr ",
            $w,
            ", ",
            $p3,
            ", ",
            $p4,
            ", 8\n",
            "vpsrldq ymm10, ",
            $p1,
            ", 4\n",
            "vpxor ",
            $w,
            ", ",
            $w,
            ", ",
            $p4,
            "\n",
            "vpxor ymm10, ymm10, ",
            $p2,
            "\n",
            "vpxor ",
            $w,
            ", ",
            $w,
            ", ymm10\n",
            "vpslldq ymm11, ",
            $w,
            ", 12\n",
            "vpsrld ymm10, ",
            $w,
            ", 31\n",
            "vpaddd ",
            $w,
            ", ",
            $w,
            ", ",
            $w,
            "\n",
            "vpor ",
            $w,
            ", ",
            $w,
            ", ymm10\n",
            "vpsrld ymm10, ymm11, 30\n",
            "vpslld ymm11, ymm11, 2\n",
            "vpxor ",
            $w,
            ", ",
            $w,
            ", ymm10\n",
            "vpxor ",
            $w,
            ", ",
            $w,
            ", ymm11\n",
            "vpaddd ymm10, ",
            $w,
            ", ",
            $k,
            "\n",
            "vmovdqa ymmword ptr [r11 + ",
            $g,
            "*32], ymm10\n",
        )
    };
}

/// Schedule group `$g` for words 32..80. `$w` holds the group eight back and receives
/// the new one: w[t] = rol(w[t-6] ^ w[t-16] ^ w[t-28] ^ w[t-32], 2), which has no
/// dependency inside the group.
macro_rules! late {
    ($g:literal, $k:literal, $w:literal, $p1:literal, $p2:literal, $p4:literal, $p7:literal) => {
        concat!(
            "vpalignr ymm10, ",
            $p1,
            ", ",
            $p2,
            ", 8\n",
            "vpxor ",
            $w,
            ", ",
            $w,
            ", ",
            $p7,
            "\n",
            "vpxor ymm10, ymm10, ",
            $p4,
            "\n",
            "vpxor ",
            $w,
            ", ",
            $w,
            ", ymm10\n",
            "vpsrld ymm10, ",
            $w,
            ", 30\n",
            "vpslld ",
            $w,
            ", ",
            $w,
            ", 2\n",
            "vpor ",
            $w,
            ", ",
            $w,
            ", ymm10\n",
            "vpaddd ymm10, ",
            $w,
            ", ",
            $k,
            "\n",
            "vmovdqa ymmword ptr [r11 + ",
            $g,
            "*32], ymm10\n",
        )
    };
}
